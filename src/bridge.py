def translate_system_toggle_wifi(action: actions.SystemToggleWifi) -> str:
    """
    Translates system.toggle_wifi into a shell command.
    - Dynamically queries the macOS hardware network ports to locate the Wi-Fi device name.
    - Enables or disables wireless interface power based on the parameter state.

    Technical Details:
    - Resolves target state parameter ("on" or "off") from SystemToggleWifiParams.
    - Constructs zsh/bash command scripting to parse output of 'networksetup -listallhardwareports'.
    - Feeds device identifier enX into 'networksetup -setairportpower' utility command.
    """
    # Extract the target wifi interface power state parameter from the validated Pydantic parameters block.
    # This attribute holds the literal string value ('on' or 'off') indicating the user's intent.
    state = action.params.state

    # Construct the shell script command sequence to toggle the hardware Wi-Fi power states.
    # We write a pipeline shell command:
    # 1. 'networksetup -listallhardwareports' query lists all hardware interfaces and port names.
    # 2. 'awk' command matches the keyword 'Wi-Fi', moves down one line to access the 'Device: enX' row, and parses the interface name.
    # 3. We store that interface name in a shell variable named 'device'.
    # 4. We evaluate if the device variable length is non-zero, then execute networksetup with -setairportpower option to toggle power state.
    cmd = (
        f"device=$(networksetup -listallhardwareports | awk '/Wi-Fi/{{getline; print $2}}'); "
        f"if [ -n \"$device\" ]; then "
        f"networksetup -setairportpower \"$device\" {state}; "
        f"fi"
    )

    audio.play_audio("audio/done.mp3", wait=False)

    # Return the formatted shell command string to be executed inside a subprocess shell shell environment.
    # We strip trailing/leading spaces to guarantee a clean string payload structure.
    return cmd.strip()

