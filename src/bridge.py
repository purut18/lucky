def parse_duration_to_minutes(duration_str: str) -> int:
    """
    Parses a duration description string (e.g. '30 minutes', '1.5 hours')
    and returns its integer equivalent in total minutes.
    
    Technical Details:
    - Normalizes strings to lowercase and runs regular expression pattern matching.
    - Searches for numbers and identifies unit markers like 'hour', 'hr', 'h' or 'minute', 'min', 'm'.
    - If hours are detected, it multiplies the numerical component by 60.
    """
    # Verify that the input duration string is valid and not empty
    if not duration_str:
        # Return a standard default duration of 60 minutes if none is provided
        return 60
    
    # Convert the string to lowercase and strip outer whitespaces to ensure consistent text matching
    s = duration_str.strip().lower()
    
    # Locate all decimal numbers or integer patterns in the string
    numbers = re.findall(r'\d+(?:\.\d+)?', s)
    # If no numbers were found in the text, return a default duration value
    if not numbers:
        # Standard fallback duration is set to 60 minutes
        return 60
        
    # Convert the first matched numerical group to a floating-point representation
    value = float(numbers[0])
    
    # If the duration string contains hour indicator tokens, scale the value to minutes
    if any(h_token in s for h_token in ["hour", "hr", "h"]):
        # Multiply the value by 60 to convert hours to minutes and return the integer value
        return int(value * 60)
        
    # Default return value is treated as minutes directly, cast to integer
    return int(value)

def format_as_heredoc(applescript_code: str) -> str:
    """
    Wraps raw AppleScript code into a POSIX shell heredoc block calling osascript.
    
    Technical Details:
    - Uses 'osascript <<\'EOF\'' which tells the shell interpreter to pass all lines
      literal-by-literal to the osascript utility without interpreting shell variables or escaping quotes.
    - This is significantly safer than using osascript -e '...' which fails when single quotes exist.
    """
    # Strip unnecessary leading/trailing newlines from the raw script to keep it neat
    cleaned_code = applescript_code.strip()
    # Return the formatted shell heredoc string block using EOF as the delimiter
    return f"osascript <<'EOF'\n{cleaned_code}\nEOF"

