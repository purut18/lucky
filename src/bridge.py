def action_from_json(json_str: str) -> Union[None, object]:
    """
    Parses a raw JSON string and converts it to a validated Pydantic action model.
    
    Technical Details:
    - Parses input using standard json.loads to extract root keys (app, action).
    - Matches keys with ACTION_MODEL_MAP to find the Pydantic class.
    - Resolves and instantiates the specific Pydantic model with strict validation.
    """
    # Parse the input string into a standard dictionary
    data = json.loads(json_str)
    # Retrieve the application name value
    app = data.get("app")
    # Retrieve the action category value
    action = data.get("action")
    
    # Locate the validation model corresponding to keys
    model_cls = ACTION_MODEL_MAP.get((app, action))
    # If no schema is registered, raise a descriptive value error
    if not model_cls:
        raise ValueError(f"No validation schema found for app: '{app}' and action: '{action}'")
        
    # Instantiate the Pydantic model, enforcing type-checks and field validation
    return model_cls.model_validate(data)

def translate_action_to_command(action_obj: object) -> Union[None, str]:
    """
    Directs a validated action object to its specific translator function.
    
    Technical Details:
    - Queries action_obj properties (app, action) to locate the translator method in ACTION_TRANSLATOR_MAP.
    - Executes the corresponding translator, returning a runnable string or None.
    """
    # Retrieve target keys from the validated model instance
    app = getattr(action_obj, "app", None)
    action = getattr(action_obj, "action", None)
    
    # Find matching translator function in mapping registry
    translator_func = ACTION_TRANSLATOR_MAP.get((app, action))
    # If no handler exists, raise value error detailing lack of bridge
    if not translator_func:
        raise ValueError(f"No translation implementation found for app: '{app}' and action: '{action}'")
        
    # Execute the translator passing the Pydantic instance and return the command string
    return translator_func(action_obj)
