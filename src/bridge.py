def translate_system_update_brightness(action: actions.SystemUpdateBrightness) -> str:
    """
    Translates system.update_brightness into a Swift-based display services command.
    - Reads the current display brightness level from the system display services.
    - Applies a relative offset, scaling the percentage value to a 0.0-1.0 float.
    - Clamps the value to ensure the target brightness is positive and between 0.0 and 1.0 (0-100%).
    - Invokes DisplayServicesSetLinearBrightness to set the final brightness.
    """
    # Extract the relative change offset amount from Pydantic action parameter fields
    amount = action.params.amount
    # Convert the percentage integer offset into a double/float fraction representation
    amount_fraction = amount / 100.0
    
    # Formulate a Swift command line string that imports private framework APIs,
    # queries current screen brightness using GetLinearBrightness, calculates the relative
    # offset adjustment, clamps results to [0.0, 1.0] range, and sets display brightness.
    script = (
        "swift -e 'import DisplayServices; "
        "var current: Float = 0.0; "
        "DisplayServicesGetLinearBrightness(0, &current); "
        f"var newBrightness = current + {amount_fraction}; "
        "if newBrightness < 0.0 { newBrightness = 0.0 }; "
        "if newBrightness > 1.0 { newBrightness = 1.0 }; "
        "DisplayServicesSetLinearBrightness(0, newBrightness)'"
    )
    # Return the clean compiled command string directly for terminal subprocess execution
    return script.strip()


